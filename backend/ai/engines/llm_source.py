"""
ai/engines/llm_source.py
========================
Tells the caller whether an explanation came from the local LLM or from the
deterministic fallback.

WHY THIS EXISTS
    Every explainability engine already degrades gracefully: if Ollama is down,
    it returns a hand-written fallback string instead of failing. That is the
    right behaviour — but it is also invisible. From the API response alone you
    cannot tell whether the local model actually ran.

    That matters twice over:
      1. Debugging. "The explanations look generic" and "Ollama isn't running"
         are the same symptom, and without this flag you cannot tell them apart.
      2. Honesty. When we tell a bank panel "this is generated by a local LLM",
         the response should be able to prove it, per request.

The engines return plain strings, so rather than changing every signature we
record the source in thread-local state for the duration of one request. FastAPI
runs each sync endpoint in its own worker thread, so this cannot bleed between
concurrent requests.
"""

from __future__ import annotations

import threading
import urllib.request

LLM = "llm"
FALLBACK = "template"

# ── Timeout / residency tuning ───────────────────────────────────────────────
# The original per-engine timeouts were 6–10 seconds. That is far too short for
# llama3:8b on laptop-class hardware: the FIRST request after Ollama starts has
# to load ~4.7 GB of weights into memory, which alone takes 15–40s. Every engine
# then "worked" — it just silently returned its fallback every time.
#
# Two fixes:
#   GENERATE_TIMEOUT  generous enough to cover a cold load and a real generation.
#   KEEP_ALIVE        tells Ollama to keep the model resident, so only the very
#                     first call pays the load cost instead of every call after
#                     an idle gap.
#
# A long timeout is safe here because every caller in this app fetches
# explanations ASYNCHRONOUSLY, after the decision is already on screen. No
# customer ever waits on the model.
GENERATE_TIMEOUT = 45
KEEP_ALIVE = "30m"
PROBE_TIMEOUT = 3


def warm_up(base_url: str = "http://localhost:11434", model: str = "llama3:latest") -> bool:
    """
    Ask Ollama to load the model without generating anything.

    Called once at application startup, in the background. Turns the first
    customer-facing explanation from a 30-second cold start into a normal one.
    """
    import json

    try:
        payload = json.dumps({"model": model, "keep_alive": KEEP_ALIVE}).encode()
        req = urllib.request.Request(
            f"{base_url}/api/generate",
            data=payload,
            headers={"Content-Type": "application/json"},
            method="POST",
        )
        with urllib.request.urlopen(req, timeout=GENERATE_TIMEOUT) as resp:
            return resp.status == 200
    except Exception:
        return False

def tidy(text: str) -> str:
    """
    Normalise whitespace in model output.

    llama3 wraps lines mid-sentence. Several engines strip newlines without
    substituting a space, which fuses the words either side — the customer sees
    "integrityand safety" or "actinglike a bully". Collapsing ALL runs of
    whitespace (newlines included) to a single space fixes it in one place.
    """
    import re

    if not text:
        return text
    return re.sub(r"\s+", " ", text).strip()


_state = threading.local()


def mark(source: str) -> None:
    """Called by an engine to record how it produced its last explanation."""
    _state.source = source


def take(default: str = FALLBACK) -> str:
    """Read and clear the recorded source. Defaults to the honest answer."""
    source = getattr(_state, "source", None)
    _state.source = None
    return source or default


def ollama_available(base_url: str = "http://localhost:11434", timeout: float = 2.0) -> bool:
    """
    Quick liveness probe for the local model server.

    Used by diagnostics only — the engines themselves just attempt the call and
    fall back, which avoids paying for a probe on every explanation.
    """
    try:
        req = urllib.request.Request(f"{base_url}/api/tags", method="GET")
        with urllib.request.urlopen(req, timeout=timeout) as resp:
            return resp.status == 200
    except Exception:
        return False
