# This does NOT run inside this repository as-is. It was written against the
# original `ai_new/` package layout and needs the training dataset, neither of
# which ships here. It is kept because the artifacts it produced are live in
# production code, and anyone auditing them should be able to see how they were
# derived.
#
# What it establishes, and what to say if asked:
#
#   * ONE-CLASS LEARNING. The autoencoder is trained ONLY on legitimate
#     transactions (is_fraud == 0). It never sees a fraud example. Fraud rows
#     are held out and used solely to validate where the thresholds land. That
#     is what makes it a genuine novelty detector rather than a second fraud
#     classifier: it flags "unlike anything normal", not "matches known fraud".
#
#   * THRESHOLDS ARE EMPIRICAL. p95 -> ANOMALOUS, p99 -> UNKNOWN_RISK, taken
#     from the distribution of reconstruction error on legitimate data. Not
#     hand-picked numbers.
#
#   * NO LEAKAGE. The scaler is fit on the training split only.
#
#   * ARCHITECTURE 22 -> 11 -> 5 -> 11 -> 22, matching TransactionAutoencoder
#     in ai/engines/zero_day_detector.py. Deliberately a plain dense
#     autoencoder with MSE loss — interpretable and fast, and it maps cleanly
#     to per-feature anomaly scores.
#
# ONE KNOWN WRINKLE. It does `torch.save(model.cpu(), path)` — the whole model
# object, not a state_dict. Pickle therefore records the class's original import
# path, `ai_new.zero_day_detector.TransactionAutoencoder`, which does not exist
# here. Loading failed with "No module named 'ai_new'" and the pipeline silently
# fell back to the statistical detector. _register_legacy_module_alias() in
# ai/engines/zero_day_detector.py aliases that path to the local class.
#
# If this is ever re-run, prefer:
#       torch.save(model.state_dict(), path)
# State dicts carry no module paths and load anywhere. The alias can then go.
